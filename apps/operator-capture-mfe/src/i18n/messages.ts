const CATALOGS: Record<string, Catalog> = { en: EN, fr: FR, de: DE, nl: NL, es: ES }

export type TranslateFn = (key: string, params?: Record<string, string | number>) => string

export const SUPPORTED_LANGUAGES = ['en', 'fr', 'de', 'nl', 'es'] as const

export const LANGUAGE_LABELS: Record<string, string> = {
  en: 'English',
  fr: 'Français',
  de: 'Deutsch',
  nl: 'Nederlands',
  es: 'Español',
}

export function languageOf(locale: string): string {
  const language = (locale || 'en').slice(0, 2).toLowerCase()
  return language in CATALOGS ? language : 'en'
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) {
    return template
  }
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  )
}

export function createTranslator(locale: string): TranslateFn {
  const language = languageOf(locale)
  const catalog = CATALOGS[language]
  return (key, params) => {
    const template = catalog[key] ?? CATALOGS.en[key] ?? key
    return interpolate(template, params)
  }
}
